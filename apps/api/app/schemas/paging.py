"""Общее для постраничных списков.

Направление сортировки одно для всех списков: дальше по конвейеру такие
же таблицы будут у глав, блоков, замечаний и выпусков, и перечисление
«asc/desc», повторённое в каждом роутере, однажды разойдётся — где-то
появится «ascending», и витрина начнёт получать 422 на один экран из
десяти.
"""

import enum


class SortOrder(str, enum.Enum):
    ASC = "asc"
    DESC = "desc"
