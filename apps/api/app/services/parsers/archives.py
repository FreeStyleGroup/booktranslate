"""Осторожная работа с ZIP-контейнерами.

DOCX и EPUB — это ZIP, а ZIP приходит от клиента и доверия не заслуживает.
Файл в пятьдесят мегабайт по правилам загрузки разворачивается в десятки
гигабайт: степень сжатия у повторяющихся байтов практически не ограничена,
и «архивная бомба» — приём известный и дешёвый. Проверять надо до чтения,
по оглавлению: `read()` уже развернёт содержимое в память.

Предел на один файл и на архив целиком разные, и оба нужны. Один файл на
гигабайт валит процесс сам по себе; тысяча файлов по мегабайту — так же,
только в обход первого предела.
"""

import zipfile

# Один распакованный файл внутри архива. Глава книги в XHTML — это сотни
# килобайт; тридцать два мегабайта на главу с огромным запасом покрывают
# книги с встроенными таблицами и оставляют бомбу снаружи.
MAX_MEMBER_BYTES = 32 * 1024 * 1024

# Весь архив в распакованном виде. Книга с иллюстрациями бывает большой,
# но не такой: превышение означает не книгу.
MAX_TOTAL_BYTES = 256 * 1024 * 1024


class ArchiveTooLargeError(Exception):
    """Распакованный размер выходит за разумные пределы."""


def check_archive(archive: zipfile.ZipFile) -> None:
    """Проверить оглавление до чтения содержимого.

    Смотрится объявленный размер: он записан в оглавлении и читается без
    распаковки. Подделанный размер не помогает нападающему — распаковка
    сверх объявленного оборвётся на пределе одного файла.
    """
    total = 0

    for entry in archive.infolist():
        if entry.file_size > MAX_MEMBER_BYTES:
            raise ArchiveTooLargeError(
                f"«{entry.filename}» распаковывается в "
                f"{entry.file_size // (1024 * 1024)} МБ — это не документ"
            )

        total += entry.file_size

        if total > MAX_TOTAL_BYTES:
            raise ArchiveTooLargeError(
                f"Архив распаковывается больше чем в {MAX_TOTAL_BYTES // (1024 * 1024)} МБ"
            )


def read_member(archive: zipfile.ZipFile, name: str) -> bytes:
    """Прочитать файл из архива, не доверяя объявленному размеру.

    Оглавление проверено заранее, но записать в него одно, а сжать другое
    никто не мешает — поэтому чтение идёт с потолком и обрывается на нём.
    """
    with archive.open(name) as handle:
        data = handle.read(MAX_MEMBER_BYTES + 1)

    if len(data) > MAX_MEMBER_BYTES:
        raise ArchiveTooLargeError(f"«{name}» больше разрешённого размера")

    return data
