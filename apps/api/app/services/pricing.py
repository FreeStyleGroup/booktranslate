"""Пересчёт расхода в деньги.

Токены хранятся, деньги считаются. Разница принципиальная: цены меняются, а
потраченное на эту книгу — исторический факт, и пересчитывать его задним
числом по новому прейскуранту значит подделывать отчёт. Поэтому в базе
лежат токены, а стоимость собирается на лету и всегда помечена как оценка.

Оценка, а не счёт, ещё и потому, что сторона поставщика считает по-своему:
пробные периоды, скидки за объём, разные ставки у облачных площадок. Число
здесь годится, чтобы понять порядок и назначить цену заказчику, а не чтобы
сверять с выставленным счётом.
"""

from dataclasses import dataclass
from math import ceil

# Цены в долларах за миллион токенов. Сверено 07.09.2026; при смене модели
# или тарифа таблицу надо обновить — молча устаревшая цена хуже её
# отсутствия, потому что выглядит как знание.
PRICES: dict[str, "Price"] = {}

# Множитель для чтения из кэша: примерно десятая часть обычного ввода. Ради
# него кэш и заводился, и в отчёте это должно быть видно.
CACHE_READ_RATIO = 0.1

# Запись в кэш дороже обычного ввода, но платится один раз.
CACHE_WRITE_RATIO = 1.25

# Веб-поиск оплачивается запросами, а не токенами: 10 долларов за тысячу
# запросов. Сверено 07.09.2026. В счётчиках токенов его не видно вовсе, и
# отчёт без него занижал бы стоимость наполнения каталога.
WEB_SEARCH_USD_PER_1000 = 10.0


@dataclass(frozen=True, slots=True)
class Price:
    """Ставки одной модели, долларов за миллион токенов."""

    input_usd: float
    output_usd: float


PRICES.update(
    {
        "claude-opus-5": Price(input_usd=5.00, output_usd=25.00),
        "claude-sonnet-5": Price(input_usd=2.00, output_usd=10.00),
        "claude-haiku-4-5": Price(input_usd=1.00, output_usd=5.00),
    }
)

MILLION = 1_000_000


# ── Смета до перевода ──
#
# Сколько токенов уйдёт на книгу, заранее не знает никто: счёт зависит от
# языка (латиница даёт вчетверо больше символов на токен, чем кириллица),
# от разметки внутри абзацев и от того, сколько терминов подцепится к
# сегменту. Поэтому смета считается по худшему из правдоподобных раскладов
# и отдаётся как оценка сверху. Направление выбрано осознанно: смета,
# оказавшаяся выше счёта, — приятная новость, а оказавшаяся ниже — разговор
# с заказчиком о доплате.

# Символов на токен в исходнике. Три — середина между кириллицей (около
# двух) и латиницей (около четырёх), смещённая в сторону кириллицы.
SOURCE_CHARS_PER_TOKEN = 3.0

# То же для перевода. Перевод на русский считается по кириллице: это
# основное направление работы, и занижать тут нечего.
TARGET_CHARS_PER_TOKEN = 2.0

# Насколько перевод длиннее исходника в символах. Русский текст обычно
# длиннее английского примерно на десятую часть.
TARGET_GROWTH = 1.15

# Надбавка на обвязку запроса: номера сегментов, их тип, термины и сам
# JSON. Системные правила сюда не входят — они кэшируются и оплачиваются
# один раз на книгу.
PROMPT_EXTRAS = 1.15


@dataclass(frozen=True, slots=True)
class Forecast:
    """Смета на перевод: оценка сверху, а не счёт."""

    input_tokens: int
    output_tokens: int
    usd: float | None


def forecast(model: str, *, characters: int, context_segments: int) -> Forecast:
    """Во что обойдётся перевод текста такого объёма.

    `characters` — только то, за что придётся платить: повторы внутри
    книги и совпадения с памятью переводов модели не отправляются вовсе,
    и включать их в смету значило бы продавать воздух.

    `context_segments` — сколько соседей прикладывается к сегменту с каждой
    стороны (`TRANSLATION_CONTEXT_SEGMENTS`). Параметром, а не чтением
    настроек здесь: смета должна считаться и проверяться без них.
    """
    prompt_chars = characters * (1 + 2 * context_segments) * PROMPT_EXTRAS

    input_tokens = ceil(prompt_chars / SOURCE_CHARS_PER_TOKEN)
    output_tokens = ceil(characters * TARGET_GROWTH / TARGET_CHARS_PER_TOKEN)

    return Forecast(
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        usd=estimate_usd(model, input_tokens=input_tokens, output_tokens=output_tokens),
    )


def estimate_usd(
    model: str,
    *,
    input_tokens: int,
    output_tokens: int,
    cached_input_tokens: int = 0,
    cache_write_tokens: int = 0,
    searches: int = 0,
) -> float | None:
    """Оценка стоимости перевода или справки.

    `None` означает «модель не в прейскуранте» — и это честнее нуля:
    заглушка ничего не стоит, а неизвестная модель стоит неизвестно
    сколько, и показывать её как бесплатную нельзя.
    """
    price = PRICES.get(model)

    if price is None:
        return None

    tokens = (
        input_tokens * price.input_usd
        + cached_input_tokens * price.input_usd * CACHE_READ_RATIO
        + cache_write_tokens * price.input_usd * CACHE_WRITE_RATIO
        + output_tokens * price.output_usd
    )

    return round(tokens / MILLION + searches * WEB_SEARCH_USD_PER_1000 / 1000, 4)
