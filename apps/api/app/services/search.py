"""Подстрока для поиска по образцу.

`%` и `_` в LIKE — это не буквы, а подстановки: «любая последовательность» и
«любой знак». Введённые человеком, они превращают поиск по фамилии в поиск
по всей таблице — инъекции нет (запрос параметризован), но одно нажатие
клавиши заставляет базу читать всё подряд.
"""

# Экранирующий знак задаётся явно в `escape=`: у разных баз умолчание своё.
ESCAPE = "\\"


def contains(query: str) -> str:
    """Образец «содержит подстроку» с обезвреженными подстановками."""
    safe = query.strip().replace(ESCAPE, ESCAPE * 2).replace("%", ESCAPE + "%")
    safe = safe.replace("_", ESCAPE + "_")

    return f"%{safe}%"
