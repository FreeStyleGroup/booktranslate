"""Общее для сборки переведённого документа.

Сборка — обратная сторона разбора, и она наследует его ограничение.
Разборщик отдаёт текст блока строкой: абзац, ячейка, заголовок. Внутреннего
оформления — полужирного слова посреди фразы, ссылки на трёх словах — в
этой строке нет и не было, поэтому вернуть его при сборке неоткуда.
Сохраняется то, что разбор действительно знал: порядок, тип блока, стиль
абзаца, структура таблиц.

Это осознанная граница, а не недоделка. Хранить разметку внутри сегмента
значит показывать её редактору и требовать не сломать при правке; сегмент
перестаёт быть текстом и становится кодом. Выбор в пользу текста сделан на
разборе, и здесь он просто доводится до конца.
"""

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from app.models.segment import SegmentKind


class ExportError(Exception):
    """Собрать документ не удалось."""


@dataclass(frozen=True, slots=True)
class TranslatedBlock:
    """Блок исходника вместе с его переводом.

    Собирается из сегментов: длинный абзац при разборе резался на несколько,
    и здесь они снова становятся одним блоком — в файл идёт абзац, а не
    строки, на которые его делили ради удобства перевода.
    """

    text: str
    kind: SegmentKind = SegmentKind.PARAGRAPH
    location: dict[str, Any] = field(default_factory=dict)
    # Переведён ли блок на самом деле. Ложь означает, что в тексте лежит
    # исходник: документ собирают до конца перевода и об этом предупреждают.
    translated: bool = True


@dataclass(frozen=True, slots=True)
class Rendered:
    content: bytes
    media_type: str
    # Расширение вместе с точкой: подставляется к имени исходного файла.
    suffix: str


class Renderer(Protocol):
    """Сборщик одного формата на выходе."""

