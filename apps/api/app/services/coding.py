"""Выдача постоянных номеров для кодов книг, глав, блоков и замечаний.

Номер выдаёт только сервер и только этим способом. Причина в том, что
коды уходят наружу — в документы, в переписку, в номер ошибки целиком, —
и выданный номер не должен достаться второй записи.

Очевидный способ «взять максимум и прибавить единицу» этого не
обеспечивает: два одновременных запроса прочитают одно и то же значение и
оба запишут следующее. Здесь увеличение и чтение происходят одним
запросом `INSERT … ON CONFLICT DO UPDATE … RETURNING`: Postgres берёт
блокировку строки на время транзакции, и второй запрос ждёт первого, а не
повторяет его результат.

Сервис выдаёт число, а не готовый код. Собирать строку — дело того, кто
её выдаёт: приставка и ширина у книги, главы и замечания разные, а у
номера ошибки код вообще составной (`BK01-CH03-ERR-0001`). Держать все
форматы здесь значило бы собрать в одном месте знание обо всех этапах
процесса.
"""

import uuid

from sqlalchemy import func
from sqlalchemy.dialects.postgresql import insert

from app.models.coding import CodeCounter, CodeKind
from app.services.base import TenantService


class CodeAllocator(TenantService):
    async def next(self, kind: CodeKind, owner_id: uuid.UUID) -> int:
        """Следующий свободный номер в этой области нумерации.

        `owner_id` — тот, внутри кого нумерация сквозная: организация для
        книг, книга для глав, глава для блоков и замечаний.

        Транзакцией управляет вызывающий. Номер и запись, ради которой он
        взят, обязаны сохраниться вместе: отдельная фиксация счётчика
        оставила бы дыру в нумерации при откате, а отдельная фиксация
        записи — две записи с одним номером.
        """
        return (await self.reserve(kind, owner_id, 1))[0]

    async def reserve(self, kind: CodeKind, owner_id: uuid.UUID, count: int) -> range:
        """Подряд идущие номера для `count` записей — одним запросом.

        Глава — это сотни блоков. Номер на каждый отдельным запросом — сотни
        походов в базу ради того, что делается одним: счётчик сдвигается на
        `count`, и его новое значение — последний номер выданного отрезка.
        Номера отрезка подряд, и чужая выдача между ними встать не может:
        строка счётчика заблокирована до конца транзакции.
        """
        if count < 1:
            return range(0)

        statement = (
            insert(CodeCounter)
            .values(
                organization_id=self.organization_id,
                kind=kind,
                owner_id=owner_id,
                last_value=count,
            )
            .on_conflict_do_update(
                constraint="code_counter_scope",
                # Ссылка на колонку таблицы, а не на `excluded`: нужно
                # увеличить уже сохранённое значение, а не подставить
                # число из неудавшейся вставки.
                set_={"last_value": CodeCounter.last_value + count, "updated_at": func.now()},
            )
            .returning(CodeCounter.last_value)
        )

        result = await self._session.execute(statement)

        # Ровно одна строка: upsert с RETURNING либо вставляет, либо
        # обновляет, третьего исхода нет. `scalar_one` не подстраховка,
        # а запись этого требования: пустой ответ означал бы, что номера
        # не выданы, и продолжать с подставленными нельзя — две записи
        # получили бы один код.
        last = result.scalar_one()

        return range(last - count + 1, last + 1)
