"""Ошибки предметной области.

Сервисы не знают про HTTP: они говорят, что произошло, а перевод в коды
ответа делает слой обработчиков. Иначе сервис нельзя вызвать ни из
фоновой задачи, ни из консольной команды, не таща за собой FastAPI.
"""


class DomainError(Exception):
    """Базовая ошибка предметной области."""


class AuthError(DomainError):
    """Не удалось подтвердить личность: 401."""


class AccessDeniedError(DomainError):
    """Личность известна, прав не хватает: 403.

    Имя не повторяет встроенное PermissionError намеренно: у него другой
    смысл (доступ к файлу или ресурсу ОС), и совпадение сбивало бы с толку
    при чтении except-веток.
    """


class NotFoundError(DomainError):
    """Объекта нет либо он принадлежит другой организации: 404.

    Второй случай намеренно не отличается от первого: ответ «403 чужое»
    подтверждает, что объект существует, и позволяет перебором выяснить
    состав чужих данных.
    """


class ConflictError(DomainError):
    """Действие противоречит текущему состоянию: 409."""


class InvalidInputError(DomainError):
    """Данные разобрались, но по смыслу не годятся: 400.

    Не то же самое, что ошибка схемы (её ловит Pydantic и отвечает 422):
    здесь тип верный, а содержимое бессмысленно — например пустой файл.
    """


class PayloadTooLargeError(DomainError):
    """Загруженное превышает разрешённый размер: 413."""


class UnsupportedFormatError(DomainError):
    """Формат файла не поддерживается: 415."""
