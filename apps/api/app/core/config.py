"""Настройки приложения.

Всё, что зависит от среды, читается из переменных окружения: приложение
одинаково запускается в контейнере, на сервере и в тестах, а секреты не
лежат в коде.
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    app_name: str = "BookTranslate API"
    environment: str = "development"
    debug: bool = False

    # Адрес базы. Драйвер asyncpg указан прямо в схеме: SQLAlchemy выбирает
    # синхронный или асинхронный движок именно по ней, и без "+asyncpg"
    # приложение падает не при старте, а на первом запросе.
    database_url: str = (
        "postgresql+asyncpg://booktranslate:booktranslate@localhost:5432/booktranslate"
    )

    # Домены витрины, которым разрешён доступ к API из браузера.
    cors_origins: list[str] = ["http://localhost:3000"]

    # Имена, под которыми API отвечает. Звёздочка годится для разработки; в
    # рабочей среде список закрывает подмену заголовка Host, на которой
    # строятся отравление кэша и подделка ссылок в письмах.
    allowed_hosts: list[str] = ["*"]

    # ── Частота запросов ──
    # Потолок на один адрес в минуту: общий и отдельный, строгий, для входа
    # и регистрации. Проверка пароля считается Argon2id и по замыслу
    # дорогая — без отдельной меры десяток запросов кладёт сервер целиком.
    rate_limit_per_minute: int = 300
    auth_rate_limit_per_minute: int = 10

    # Ключ подписи токенов. Значение по умолчанию годится только для
    # разработки: в рабочей среде переменная обязательна, иначе подделать
    # токен сможет любой, кто читал этот файл. Проверка — в validate().
    jwt_secret: str = "dev-secret-change-me"
    jwt_algorithm: str = "HS256"

    # Короткий срок жизни доступа и длинный — обновления. Украденный
    # access-токен протухает за четверть часа, а refresh лежит в базе и
    # отзывается: у него есть чему протухнуть принудительно.
    access_token_ttl_minutes: int = 15
    refresh_token_ttl_days: int = 30

    # Окно, внутри которого повторный приход по только что заменённому
    # refresh-токену считается гонкой клиента, а не кражей. Две вкладки,
    # открытые одновременно без access-cookie, шлют два обновления с одним
    # токеном; без окна второе гасило бы все сеансы человека — и чужая
    # страница могла бы устраивать это нарочно. Внутри окна повтор просто
    # отвергается, вне его — сброс всех сеансов, как и положено при краже.
    refresh_reuse_grace_seconds: int = 10

    # Где лежат исходные файлы документов. Каталог на диске — временное
    # решение на время разработки и одного сервера; интерфейс хранилища
    # рассчитан на замену объектным (см. app/services/storage.py).
    storage_root: str = "./var/storage"

    # Потолок размера загружаемого файла. Проверяется на лету, по мере
    # чтения: узнавать о превышении после того, как гигабайт уже принят на
    # диск, поздно и дорого.
    max_upload_mb: int = 50

    # Размер сегмента в знаках. Сегмент — это то, что уходит в модель одним
    # куском и что редактор видит одной строкой, поэтому крайности вредны
    # одинаково: слишком короткий лишает перевод контекста и дробит правку,
    # слишком длинный упирается в окно модели и заставляет человека читать
    # абзац целиком ради одной запятой. Целевое значение — ориентир, по
    # которому режутся длинные абзацы; жёсткий предел не превышается никогда,
    # даже если внутри нет ни одной границы предложения.
    segment_target_chars: int = 1200
    segment_hard_limit_chars: int = 3000

    # Сколько сегментов уходит провайдеру одним вызовом. У любого настоящего
    # провайдера накладные расходы на вызов сопоставимы с переводом короткой
    # фразы, поэтому пачка обязательна; верхняя граница — окно модели.
    translation_batch_size: int = 20

    # Сколько сегментов разрешено перевести одним запуском. Потолок не от
    # злого умысла, а от повторного нажатия и цикла в чужом скрипте: каждый
    # прогон стоит денег, и «перевести всё заново» должно упираться в явный
    # предел. Книга в четыреста страниц — это примерно шесть тысяч сегментов.
    translation_max_segments_per_run: int = 20000

    # Сколько сегментов берётся за один вызов перевода, если клиент не
    # попросил иначе. Книга переводится не одним запросом, а циклом вызовов
    # «до нуля»: обратный прокси режет соединение через четверть часа, и
    # один запрос на шесть тысяч сегментов до ответа не доживает. Две сотни
    # — это десять пачек, несколько минут работы модели, с запасом до
    # предела прокси.
    translation_default_limit: int = 200

    # Через сколько минут без отметки документ, застрявший в «разбирается»
    # или «переводится», считается брошенным. Живой прогон отмечается в
    # документе после каждой пачки, так что полчаса тишины — это упавший
    # процесс, а не длинная пачка. Такой документ разрешено взять повторно
    # с force=true, не дожидаясь перезапуска.
    translation_stale_minutes: int = 30

    # Сколько соседних сегментов уходит в запрос вместе с переводимым. Без
    # соседей «он», «указанный выше» и опущенное подлежащее переводятся
    # наугад; с ними растёт длина запроса. Двойка — компромисс: абзац перед
    # и абзац после снимают почти всю неоднозначность.
    translation_context_segments: int = 2

    # Сколько действующих терминов разрешено брать в работу. Каждый термин
    # превращается в регулярное выражение и прогоняется по каждому сегменту:
    # чужая термбаза, загруженная целиком, умножает работу на порядок и
    # ничего не даёт — в книге столько терминов не встречается.
    glossary_max_active_terms: int = 5000

    # Потолок на одну загрузку словаря. Термбаза на сотни тысяч строк — это
    # не глоссарий книги, а чужая база целиком: грузить её одним запросом
    # значит держать транзакцию открытой минутами.
    max_import_terms: int = 20000

    # ── Провайдер перевода ──
    # «stub» — заглушка: конвейер работает целиком, но ничего не стоит и
    # никуда не ходит. Умолчание именно такое: разработка и CI не должны
    # ходить в сеть и тратить деньги, а рабочая среда задаёт это явно.
    translation_provider: str = "stub"

    # Ключ можно не задавать: клиент модели сам возьмёт его из окружения
    # (ANTHROPIC_API_KEY) или из профиля, настроенного на машине.
    anthropic_api_key: str = ""
    anthropic_model: str = "claude-opus-5"

    # Адрес совместимого шлюза. Пусто — обращаться в Anthropic напрямую.
    # Шлюз (AITunnel и подобные) принимает те же запросы к /v1/messages, но
    # оплачивается в рублях и доступен из России без обходных путей.
    # Ключ шлюза передаётся заголовком «Authorization: Bearer», а не
    # «x-api-key», — это не мелочь: с неверным заголовком шлюз отвечает
    # отказом в доступе, и выглядит это как неправильный ключ.
    anthropic_base_url: str = ""

    # Потолок ответа. Пачка, в него не уместившаяся, переводится половинами:
    # обрезанный перевод выглядит законченным, и это худший вид ошибки.
    anthropic_max_tokens: int = 16000

    # Глубина работы модели: low | medium | high | xhigh | max. Пусто —
    # умолчание модели. Значение подбирается на реальной книге: технический
    # перевод не задача на рассуждение, но и не механическая подстановка.
    anthropic_effort: str = ""

    # Перевод книги — сотни запросов подряд. Сетевой сбой или ограничение
    # частоты на середине не должны ронять весь документ, поэтому повторов
    # больше, чем в клиенте по умолчанию, а таймаут — с запасом на длинную
    # пачку.
    anthropic_max_retries: int = 5
    anthropic_timeout_seconds: float = 600.0

    # Запасная модель на случай отказа по правилам безопасности. Технический
    # текст изредка задевает их темы — взрывозащита, химия, досмотровое
    # оборудование, — и без запасного пути такая пачка просто не
    # переведётся. Выключается, если у организации нет доступа к этой
    # возможности: иначе запрос отвергается целиком.
    anthropic_use_fallbacks: bool = True

    # ── Каталог терминов ──
    # Где смотреть незнакомое слово: «offline» — нигде (каталог наполняется
    # руками и импортом словарей), «claude» — модель с выходом в сеть.
    # Умолчание закрытое: поиск ходит в интернет, оплачивается отдельно от
    # перевода и у заказчика с закрытым контуром может быть запрещён вовсе.
    term_lookup_provider: str = "offline"

    # Потолок ответа на одну справку. Справка — это несколько предложений и
    # список источников, а не глава: разбухший ответ означает, что модель
    # пересказывает найденное вместо того, чтобы отвечать.
    term_lookup_max_tokens: int = 4000

    # Сколько терминов ищется одновременно. Поиск идёт в сеть и занимает
    # секунды; по одному пришлось бы ждать минутами, всеми сразу — упереться
    # в ограничение частоты и получить отказ по всей пачке.
    term_lookup_concurrency: int = 4

    # Сколько справок разрешено запросить одним обращением. Прогон по списку
    # кандидатов стоит денег и времени, и «поискать всё» на книге в четыреста
    # страниц должно упираться в явный предел, а не в терпение человека.
    term_lookup_batch: int = 25

    @property
    def max_upload_bytes(self) -> int:
        return self.max_upload_mb * 1024 * 1024

    def validate_runtime(self) -> None:
        """Проверки, которые нельзя выразить типом поля.

        Вызывается при сборке приложения: лучше не подняться совсем, чем
        подняться в рабочей среде с ключом подписи из примера.
        """
        if self.environment == "development":
            return

        if self.jwt_secret == "dev-secret-change-me":
            raise RuntimeError(
                "JWT_SECRET не задан: в среде «" + self.environment + "» "
                "запуск с ключом по умолчанию запрещён"
            )

        # HS256 держится только на длине ключа: короткий подбирается
        # офлайн по любому выданному токену, и дальше подпись подделывается
        # для кого угодно. 32 байта — нижняя граница из RFC 7518, bootstrap
        # генерирует 64 шестнадцатеричных знака.
        if len(self.jwt_secret.encode()) < 32:
            raise RuntimeError(
                "JWT_SECRET короче 32 байт: сгенерируйте его командой openssl rand -hex 32"
            )

        # Звёздочка в источниках вместе с разрешёнными печеньями — это
        # приглашение читать API с любого сайта от имени вошедшего. Пишется
        # такое обычно «чтобы заработало» и остаётся навсегда.
        if "*" in self.cors_origins:
            raise RuntimeError("CORS_ORIGINS=* вне разработки запрещён: перечислите домены витрины")

        if "*" in self.allowed_hosts:
            raise RuntimeError(
                "ALLOWED_HOSTS=* вне разработки запрещён: перечислите имена, под "
                "которыми отвечает API"
            )


@lru_cache
def get_settings() -> Settings:
    """Настройки читаются один раз за процесс.

    Без кеша каждый запрос заново разбирал бы окружение и .env-файл.
    """
    return Settings()
