/* Запрос пришёл со своей страницы или с чужой.
 *
 * У обработчика маршрута, в отличие от серверного действия, встроенной
 * защиты от запроса с чужого сайта нет. Без проверки чужая страница
 * отправляет форму сюда и делает в браузере жертвы то, на что у неё есть
 * печенья: открывает сеанс под чужой учётной записью, загружает файл в
 * чужое пространство. `SameSite` от этого не спасает — она ограничивает
 * отправку печений, а не то, что с ними делают.
 *
 * Отдельным файлом, потому что проверка нужна каждому обработчику, а
 * скопированная в каждый она однажды разойдётся — и разойдётся молча, в
 * сторону «пропускаем».
 */
export function foreign(request: Request): boolean {
  const origin = request.headers.get("origin");
  const host = request.headers.get("host");

  // Запрос без источника к делу отношения не имеет: браузер ставит
  // заголовок на каждой отправке формы и на каждом fetch.
  if (origin === null || host === null) {
    return true;
  }

  try {
    return new URL(origin).host !== host;
  } catch {
    return true;
  }
}
