/* Языки витрины.
 *
 * Два: русский и английский. Русский — язык по умолчанию, и живёт он на
 * голых адресах (`/`, `/login`); английский — с приставкой `/en`.
 *
 * 🔥 Приставки у русского нет намеренно. Сайт уже год как проиндексирован
 * по адресу `booktranslate.ru/`, и переезд на `/ru/` означал бы либо
 * потерю позиций, либо цепочку перенаправлений на каждой ссылке. Языковая
 * приставка нужна только новому языку.
 *
 * Язык — в адресе, а не в печенье. Причины две. Поисковик обязан видеть
 * английскую страницу отдельным документом, иначе английской версии для
 * него не существует. И ссылка, посланная коллеге, должна открыться на том
 * же языке, на каком её скопировали, — с печеньем она открылась бы на
 * языке читателя.
 */

export const LOCALES = ["ru", "en"] as const;

export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "ru";

/** Приставка английских адресов — без завершающей косой черты. */
const EN_PREFIX = "/en";

export function isLocale(value: string | undefined | null): value is Locale {
  return value === "ru" || value === "en";
}

/** Язык адреса: `/en/login` — английский, всё остальное — русский. */
export function localeOf(pathname: string): Locale {
  return pathname === EN_PREFIX || pathname.startsWith(`${EN_PREFIX}/`) ? "en" : DEFAULT_LOCALE;
}

/** Адрес страницы на этом языке.
 *
 * Принимает путь без приставки (`/login`) и возвращает его же для русского
 * либо с приставкой для английского. Ради него ссылки в разметке пишутся
 * через вызов, а не строкой: ссылка «/login» на английской странице увела
 * бы человека обратно в русскую половину, и заметить это можно только
 * пройдя весь путь целиком.
 */
export function localePath(locale: Locale, path: string): string {
  if (locale === DEFAULT_LOCALE) {
    return path;
  }

  // «/» — это корень английской половины, то есть «/en», а не «/en/».
  return path === "/" ? EN_PREFIX : `${EN_PREFIX}${path}`;
}

/** Путь без языковой приставки: `/en/login` → `/login`, `/en` → `/`. */
export function basePath(pathname: string): string {
  if (localeOf(pathname) === DEFAULT_LOCALE) {
    return pathname;
  }

  return pathname.slice(EN_PREFIX.length) || "/";
}

/** Тот же адрес на другом языке — для переключателя в шапке.
 *
 * Именно тот же: человек, переключивший язык на странице регистрации,
 * должен остаться на регистрации, а не уехать на главную. Возврат на
 * главную — самая частая ошибка языковых переключателей и самая
 * раздражающая.
 */
export function switchPath(pathname: string, to: Locale): string {
  return localePath(to, basePath(pathname));
}

/** Подставить значения в строку словаря: `«{org}»` → `«Бюро»`.
 *
 * Строки с подстановками нельзя собирать склейкой в разметке: порядок слов
 * в языках разный, и «приглашает вас как» в английском стоит не там, где в
 * русском. Поэтому в словаре лежит целая фраза с местами для значений.
 *
 * 🔥 Живёт здесь, а не рядом со словарями, намеренно: этот файл не тянет за
 * собой ни одного словаря, и браузерным частям страницы можно брать
 * подстановку отсюда, не увозя с собой оба языка целиком.
 */
export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in values ? String(values[key]) : whole,
  );
}
