import type { ReactNode } from "react";

import { dictionary } from "../i18n";

/* Английская половина сайта.
 *
 * Слой существует ради одной строки — атрибута языка. У документа он
 * русский (`app/layout.tsx`), и оставить английские страницы под ним
 * нельзя: экранный диктор прочтёт английский текст русскими правилами
 * чтения, а браузер предложит перевести страницу, которая и так на языке
 * читателя.
 *
 * 🔥 Обёрткой, а не атрибутом у `<html>`, потому что разметку документа
 * рисует корневой слой, а он один на весь сайт и о вложенном адресе не
 * знает. `lang` — обычный наследуемый атрибут: объявленный на узле, он
 * действует на всё, что внутри, и это ровно то, что здесь нужно. Обёртка
 * при этом ничего не ломает: у `body` обычный поток, и лишний блок в нём
 * не создаёт ни отступов, ни ограничений ширины.
 *
 * Метаданные страниц — в самих страницах: у каждой свой заголовок,
 * описание и канонический адрес.
 */
export default function EnglishLayout({ children }: { children: ReactNode }) {
  return <div lang={dictionary("en").htmlLang}>{children}</div>;
}
